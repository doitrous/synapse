/**
 * Authored medicine game packs.
 *
 * These packs are static content: gameplay code may shuffle, score and render
 * them, but it never invents medical facts. New packs should come from the
 * content/import pipeline and pass `validateMiniGamePack` before they are shown
 * to students.
 *
 * Pure module: no React, no storage, no clock.
 */

import { seededRandom, shuffle } from './seededRandom.ts'

export type MiniGameKind = 'clinical_sequence' | 'mechanism_chain' | 'red_flag_sort'

interface BasePack {
  id: string
  kind: MiniGameKind
  title: string
  subjectId: string
  topic: string
  summary: string
  source: {
    label: string
    reviewedBy: string
  }
}

export interface OrderedStep {
  id: string
  text: string
}

export interface OrderedMiniGamePack extends BasePack {
  kind: 'clinical_sequence' | 'mechanism_chain'
  prompt: string
  steps: OrderedStep[]
  explanation: string
}

export interface RedFlagFinding {
  id: string
  text: string
  lane: 'urgent' | 'routine'
  rationale: string
}

export interface RedFlagSortPack extends BasePack {
  kind: 'red_flag_sort'
  prompt: string
  lanes: Record<RedFlagFinding['lane'], string>
  findings: RedFlagFinding[]
}

export type MiniGamePack = OrderedMiniGamePack | RedFlagSortPack

