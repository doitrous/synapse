export function validateMiniGamePack(pack: MiniGamePack): string[] {
  const errors: string[] = []
  if (!pack.id.trim()) errors.push('id is required')
  if (!pack.title.trim()) errors.push(`${pack.id}: title is required`)
  if (!pack.subjectId.trim()) errors.push(`${pack.id}: subjectId is required`)
  if (!pack.source.label.trim() || !pack.source.reviewedBy.trim()) errors.push(`${pack.id}: reviewed source metadata is required`)

  if (pack.kind === 'red_flag_sort') {
    if (!pack.lanes.urgent.trim() || !pack.lanes.routine.trim()) errors.push(`${pack.id}: both red-flag lanes are required`)
    if (pack.findings.length < 4) errors.push(`${pack.id}: at least four findings are required`)
    const lanes = new Set(pack.findings.map((finding) => finding.lane))
    if (!lanes.has('urgent') || !lanes.has('routine')) errors.push(`${pack.id}: both urgent and routine findings are required`)
    for (const finding of pack.findings) {
      if (!finding.id.trim() || !finding.text.trim() || !finding.rationale.trim()) errors.push(`${pack.id}: every finding needs id, text and rationale`)
    }
    return errors
  }

  if (pack.steps.length < 3) errors.push(`${pack.id}: at least three ordered steps are required`)
  for (const step of pack.steps) {
    if (!step.id.trim() || !step.text.trim()) errors.push(`${pack.id}: every step needs id and text`)
  }
  if (new Set(pack.steps.map((step) => step.id)).size !== pack.steps.length) errors.push(`${pack.id}: step ids must be unique`)
  return errors
}

export function validMiniGamePacks(kind?: MiniGameKind): MiniGamePack[] {
  return MINI_GAME_PACKS.filter((pack) => (!kind || pack.kind === kind) && validateMiniGamePack(pack).length === 0)
}

export function shuffledStepIds(pack: OrderedMiniGamePack, seed: number): string[] {
  return shuffle(pack.steps.map((step) => step.id), seededRandom(seed))
}

export function scoreOrderedSteps(pack: OrderedMiniGamePack, submittedIds: string[]) {
  const correct = pack.steps.map((step) => step.id)
  let exactPositions = 0
  for (let i = 0; i < correct.length; i++) {
    if (submittedIds[i] === correct[i]) exactPositions++
  }
  return {
    exactPositions,
    total: correct.length,
    complete: submittedIds.length === correct.length && submittedIds.every((id) => correct.includes(id)),
    correct,
  }
}

export function scoreRedFlagSort(pack: RedFlagSortPack, placements: Record<string, RedFlagFinding['lane']>) {
  let correct = 0
  const results = pack.findings.map((finding) => {
    const selected = placements[finding.id]
    const matched = selected === finding.lane
    if (matched) correct++
    return { finding, selected, correct: matched }
  })
  return { correct, total: pack.findings.length, results }
}
