/**
 * Build every batch for one Kasr module from the papers registered in
 * `seeds/registry.ts`.
 *
 * One command for the whole module, so adding a paper is adding a seed file and
 * a line in the registry — never a new script with its own idea of what a field
 * means. A concept batch is per module, because a concept belongs to what
 * teaches it; a written batch is per paper, because a question belongs to its
 * sitting.
 *
 *   node --experimental-strip-types scripts/kasr/build-batches.ts "101 ISK"
 *   node --experimental-strip-types scripts/kasr/build-batches.ts "102 INT"
 *
 * The module is **required**, and that is the point. Five lanes share this file
 * and each owns one module's batches; a bare run rewrote every registered
 * module's output, so one lane regenerating its own work silently rewrote a
 * neighbour's committed batch underneath them. There is no case where somebody
 * wants that and cannot ask for it a module at a time, so the convenience is
 * not worth the hazard.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import {
  MODULES, mintConceptId, moduleOf, partsKey, subjectCollisions, subjectForPath,
  type KasrSubject, type ModuleRef, type Paper, type Seed, type SourceRef,
} from './seeds/types.ts'
import { batchFile, conceptBlock, mcqBlock, mcqConceptBlock, writtenBlock } from './emit.ts'
import type { BankRow, McqLeafSeed } from './seeds/mcq.ts'
import { REGISTRATIONS } from './seeds/registry.ts'
import type { MediaRequest } from './seeds/from-json.ts'
import { loadLinks, unsupportedClaims } from './seeds/links.ts'
import { ARTICLE_FOR_CONCEPT } from './seeds/articles.ts'
import { SITTING_SIGNALS } from './seeds/sittings.ts'

const OUT = 'docs/Kasr-Source-Imports'
const OUT_ROOT = 'docs/Kasr-Source-Imports'

/** A module ID as it appears in a filename: `101 ISK` is `101-ISK`. */
const fileSlug = (module: string) => module.replace(/\s+/g, '-')

/**
 * What each article offers as further reading, read from the articles.
 *
 * A concept's `relatedArticleIds` is further reading, and the honest answer is
 * whatever its teaching article already points at — every one of the 77 carries
 * a `related_articles` list saying why each connects. Derived rather than typed,
 * so it cannot drift from the articles it describes.
 */
function furtherReading(): Map<string, string[]> {
  const dir = `${OUT_ROOT}/article`
  const out = new Map<string, string[]>()
  if (!existsSync(dir)) return out
  for (const name of readdirSync(dir).filter((one) => one.endsWith('.md'))) {
    for (const block of readFileSync(`${dir}/${name}`, 'utf8').split(/^\s*---\s*$/m)) {
      const id = block.match(/## id\n(\S+)/)?.[1]
      const related = block.match(/## related_articles\n([\s\S]*?)(?=\n## |$)/)?.[1] ?? ''
      if (!id) continue
      out.set(id, [...new Set([...related.matchAll(/^(ART-[A-Z0-9-]+)/gm)].map((m) => m[1]))])
    }
  }
  return out
}


/**
 * The line every generated batch carries, and the sweep's only licence to delete.
 *
 * One constant rather than three string literals, because the sweep tests for
 * it: if a header and the test drift apart, the sweep either deletes nothing
 * (harmless, visible) or — if a hand-authored file ever came to contain the
 * literal — deletes something it must not. Same string, one place.
 */
const GENERATED_BY = 'Generated by scripts/kasr/build-batches.ts'

/**
 * The filename each tier gets.
 *
 * One prefix per tier. This used to be a two-way branch — end of year, or else
 * "EOM" — over four tiers, so the Baqoon third-sitting resit and a formative
 * assessment were both filed as end-of-module papers. That was wrong when it
 * was written and is about to become destructive: the real end-of-module papers
 * are entirely multiple choice and are now being seeded, and a genuine
 * `EOM-2024` would have overwritten the resit sitting under the same name with
 * nothing reporting it.
 *
 * Exhaustive over `EXAM_SOURCE_TIERS`, which is the importer's own vocabulary.
 */
const TIER_PREFIX: Record<SourceRef['tier'], string> = {
  orientation: 'ORIENTATION',
  end_of_year: 'EOY',
  end_of_module: 'EOM',
  baqoon: 'BAQOON',
  department_book: 'DEPTBOOK',
  department_questions: 'DEPTQ',
  other: 'FORMATIVE',
}

/**
 * `102-INT-EOY-2025`. Refuses rather than producing `undefined`.
 *
 * `--experimental-strip-types` erases the types without checking them, so the
 * exhaustive `Record` above is a compile-time promise the runtime never keeps:
 * a seed carrying a tier this map has no key for yields `undefined`, the batch
 * is written as `101-ISK-undefined-2022-written.md`, and **the orphan sweep
 * then deletes the real file to make room for it.** Two batches lost, no error.
 *
 * That happened to another module's committed work while the tier vocabulary
 * was being widened, and it was restored from git. A thrown error costs a
 * failed run; the silent version costs somebody else's afternoon.
 */
const slug = (paper: Paper) => {
  const prefix = TIER_PREFIX[paper.source.tier]
  if (!prefix) {
    throw new Error(
      `${paper.source.file}: tier "${paper.source.tier}" has no filename prefix. `
      + `Known tiers are ${Object.keys(TIER_PREFIX).join(', ')} — the vocabulary is `
      + `EXAM_SOURCE_TIERS in src/data/examSignal.ts, and a tier outside it is coerced `
      + `to "other" there, silently costing the paper its blueprint weight.`)
  }
  return `${fileSlug(moduleOf(paper.source).id)}-${prefix}-${paper.source.sittingYear}`
}

/**
 * Concepts, deduplicated by canonical key across every paper.
 *
 * Two papers asking the same thing are one concept with two occurrences, not
 * two concepts. The alternative splits a student's mastery across duplicates
 * and inflates the blueprint weight of whatever happens to be asked often.
 */
function concepts(module: string, papers: Paper[]) {
  const reading = furtherReading()
  const byKey = new Map<string, { paper: Paper, seed: Seed, repeats: string[] }>()

  for (const paper of papers) {
    for (const seed of paper.seeds) {
      const found = byKey.get(seed.key)
      if (!found) { byKey.set(seed.key, { paper, seed, repeats: [] }); continue }
      // The first paper's reading wins — papers are registered in priority
      // order — and the later one is recorded as another occurrence.
      found.repeats.push(
        `${paper.source.id} | ${paper.source.tier} | ${paper.source.sittingYear} | p${seed.page} | ${module}`)
    }
  }

  // Sittings known from an index rather than from a paper. They carry no
  // wording and no marks, so they can never be a question — but they are
  // evidence the thing was asked, which is what the blueprint weight is for.
  //
  // Keyed by canonical key, and the keys in it are 101's, so this is a no-op
  // for any other module rather than something needing a module of its own.
  for (const [key, signals] of Object.entries(SITTING_SIGNALS)) {
    const found = byKey.get(key)
    if (found) found.repeats.push(...signals)
  }

  // What teaches each concept and what supports it. Computed per chapter rather
  // than per question — see `seeds/links.ts` — and absent for a module that has
  // not had its evidence pass, which is not an error: the concept batch is the
  // thing you need in order to write the articles.
  const links = loadLinks(module)
  const withoutSpan = unsupportedClaims(module)

  const blocks = [...byKey.values()].map(({ paper, seed, repeats }) => {
    const id = mintConceptId(module, seed.subject, seed.key, seed.system)
    const found = links.get(id)
    // `articles.ts` is the hand-written fallback for 101, whose articles
    // predate the plan files. Where a module has a plan, the plan wins.
    const articleId = found?.articleId ?? ARTICLE_FOR_CONCEPT[id]
    return conceptBlock(paper.source, seed, repeats, {
      paperMarks: paper.seeds.reduce((sum, one) => sum + one.marks, 0),
      articleId,
      relatedArticleIds: reading.get(articleId ?? '') ?? [],
      links: found && {
        ...found,
        articleId,
        // A claim the evidence pass could not find a verbatim span for was
        // never written. Pointing at it would fail the audit with `references
        // unknown claim`, and would misrepresent the concept as supported.
        claimIds: found.claimIds.filter((claimId) => !withoutSpan.has(claimId)),
      },
    })
  })

  const repeated = [...byKey.values()].filter((entry) => entry.repeats.length).length
  const header = `Concepts for ${module}, from every paper read so far.

${papers.map((paper) => `  ${paper.source.file} — ${paper.source.tier.replace(/_/g, ' ')} ${paper.source.sittingYear}, ${paper.seeds.length} questions`).join('\n')}

${byKey.size} concepts from ${papers.reduce((sum, paper) => sum + paper.seeds.length, 0)} questions.
${repeated} of them were asked on more than one paper, and carry an exam_signal
line per sitting: repetition is the strongest blueprint evidence this corpus
holds, and it only exists once the papers are read together.

Placement is on the discipline view (DIS-ANA, DIS-HIS, DIS-EMB), which is where
basic-science material belongs; the system view is a secondary placement where
one genuinely applies. \`module_subject\` carries the Kasr curriculum position,
which does not belong in the canonical tree.

${GENERATED_BY} — edit the seeds in scripts/kasr/seeds/.`

  mkdirSync(`${OUT}/concept`, { recursive: true })
  const file = `${OUT}/concept/${fileSlug(module)}-concepts.md`
  writeFileSync(file, batchFile(header, blocks))
  return { file, count: byKey.size, repeated }
}

/** Written questions, one batch per paper: an occurrence belongs to its sitting. */
function written(paper: Paper) {
  const module = moduleOf(paper.source)
  // The same links the concept batch uses, so a question and the concept it
  // tests cannot disagree about which article teaches it.
  const links = loadLinks(module.id)
  // Seeds sharing a question number are one question testing several concepts,
  // not several questions. The paper's own numbering decides.
  const byNumber = new Map<string, Seed[]>()
  for (const seed of paper.seeds) {
    const key = `${seed.section}-${seed.q}`
    byNumber.set(key, [...(byNumber.get(key) ?? []), seed])
  }

  // A question that needs a figure carries its own request, because importing
  // is the only way a media request comes into existence — there is no create
  // form in the admin UI. The hand-apply file beside it is a convenience for a
  // question already imported, not the mechanism.
  const media = new Map<string, string[]>()
  for (const request of (paper as { mediaRequests?: MediaRequest[] }).mediaRequests ?? []) {
    const block = [
      `### ${request.heading}`,
      `Brief: ${request.brief}`,
      `Purpose: ${request.purpose}`,
      `Priority: ${request.priority}`,
      `Status: ${request.status}`,
      ...(request.kind ? [`Kind: ${request.kind}`] : []),
      ...(request.sourceDirection ? [`Source direction: ${request.sourceDirection}`] : []),
      ...(request.rights ? [`Rights: ${request.rights}`] : []),
    ].join('\n')
    media.set(request.forScheme, [...(media.get(request.forScheme) ?? []), block])
  }

  // A question the paper set as lettered options is not a written question and
  // has no column for an option here. Skipped rather than emitted as a
  // zero-mark part, and named on stdout so the omission is a fact somebody read
  // rather than a silence.
  const skipped: string[] = []
  for (const [key, seeds] of [...byNumber.entries()]) {
    const scheme = paper.schemes[partsKey(seeds[0])]
    if (scheme?.format === 'mcq_single_best') {
      skipped.push(`${partsKey(seeds[0])} (${scheme.prompt.slice(0, 48)}…)`)
      byNumber.delete(key)
    }
  }
  if (skipped.length) {
    console.log(`  ${skipped.length} single-best-answer question(s) left out of ${slug(paper)} — they belong in the MCQ route:`)
    for (const one of skipped) console.log(`    ${one}`)
  }

  const blocks = [...byNumber.values()].map((seeds) =>
    writtenBlock(
      paper,
      seeds,
      (conceptId) => links.get(conceptId)?.articleId ?? ARTICLE_FOR_CONCEPT[conceptId],
      (schemeKey) => media.get(schemeKey) ?? [],
    ))
  const total = paper.seeds.reduce((sum, seed) => sum + seed.marks, 0)
  const bySection = paper.source.sections
    .map((section) => `${[...byNumber.keys()].filter((key) => key.startsWith(`${section}-`)).length} in ${section}`)
    .join(', ')

  const header = `${paper.source.file} as sittable written questions.

Kasr Al Ainy, module ${module.id}, ${paper.source.tier.replace(/_/g, ' ')} ${paper.source.sittingYear}.
Manifest ID ${paper.source.id}. ${byNumber.size} questions, ${total} marks: ${bySection}.

${paper.source.incomplete ? `NOT the whole paper: ${paper.source.incomplete}\n\n` : ''}Transcribed, not derived — \`derived_from\` is blank throughout. The rule that a
written question may only be derived from another written question governs the
practice variants that come later, not these.

Each question carries one part worth the paper's own total, with the elements the
examiner named as its expected points. \`markWritten\` apportions the marks across
those points, so a student's score agrees with the mark on the page without
anyone inventing a per-element split the examiner never printed.

Status is Draft: these need a faculty reviewer to confirm the mark schemes before
students sit them.

Provenance is in \`source_citation\` and \`author_notes\`, which the student ledger
strips. A student is never told which paper a question came off.

${GENERATED_BY}.`

  // `written/`, not `question/`. The import *kind* is question — a written
  // question is a question with a mark scheme instead of options — but the
  // index reserves `question/` for non-written items and `written/` for these.
  // Two folders for one kind is the index's call to make, not this script's.
  mkdirSync(`${OUT}/written`, { recursive: true })
  const file = `${OUT}/written/${slug(paper)}-written.md`
  writeFileSync(file, batchFile(header, blocks))
  return { file, count: byNumber.size, marks: total }
}

/**
 * Refuse to build if one canonical key has been given two subjects.
 *
 * The subject picks only the `CON-<SYS>-` prefix, so the same key under two
 * subjects mints two IDs with the same hash behind different prefixes. Nothing
 * at import time notices, and a student's mastery of one idea splits across
 * both. Two lanes author into `seeds/mcq/` and the papers are seeded
 * separately, which is exactly the arrangement that produces it.
 *
 * Checked across every seed the build can see — papers and question-book leaves
 * together — because the two halves are where the disagreement would arise.
 * Scoped to the module being built, because two modules may legitimately give
 * one key two subjects: they are two concepts in two namespaces, which is what
 * hashing the module into the ID makes true.
 */
async function assertOneSubjectPerKey(module: string, papers: Paper[]) {
  const entries: { key: string; subject: KasrSubject; where: string }[] = []
  const byPath = new Map<string, KasrSubject>()
  for (const paper of papers) {
    for (const seed of paper.seeds) {
      entries.push({ key: seed.key, subject: seed.subject, where: paper.source.file })
      const expected = subjectForPath(seed.modulePath)
      if (expected) byPath.set(seed.key, expected)
    }
  }
  for (const { leaf, name } of await mcqLeaves(module)) {
    for (const concept of leaf.concepts) {
      entries.push({ key: concept.key, subject: concept.subject, where: `seeds/mcq/${name}` })
      const expected = subjectForPath(concept.modulePath)
      if (expected) byPath.set(concept.key, expected)
    }
  }

  // The agreed rule, checked rather than remembered. A key whose subject
  // disagrees with where it sits in the curriculum is the disagreement that
  // becomes a rival id the moment a second author files the same key correctly.
  const offRule = entries
    .map((entry) => ({ entry, expected: byPath.get(entry.key) }))
    .filter(({ entry, expected }) => expected && expected !== entry.subject)
  if (offRule.length) {
    throw new Error(
      `${offRule.length} concept(s) take a subject the curriculum path does not give:\n`
      + offRule.map(({ entry, expected }) =>
        `  ${entry.key}: ${entry.subject}, expected ${expected}  (${entry.where})`).join('\n')
      + '\nSee subjectForPath in seeds/types.ts. Change the subject, or the rule, not one file.')
  }

  const clashes = subjectCollisions(entries)
  if (!clashes.length) return
  throw new Error(
    `${clashes.length} canonical key(s) given more than one subject, which mints a rival ID for one idea:\n`
    + clashes.map((clash) =>
      `  ${clash.key}: ${clash.subjects.join(' vs ')}  (${clash.where.join(', ')})`).join('\n')
    + '\nAgree one subject per key and rerun. The key decides the concept; the subject only picks its prefix.')
}

/**
 * Refuse two papers that would write to the same batch file.
 *
 * The filename carries only module, tier and year, so two sittings of one tier
 * in one year — a first and second sitting, or a paper filed under the wrong
 * tier — silently overwrite each other, and the survivor looks complete.
 */
function assertNoSlugCollision(papers: Paper[]) {
  const byFile = new Map<string, string[]>()
  for (const paper of papers) {
    const file = slug(paper)
    byFile.set(file, [...(byFile.get(file) ?? []), paper.source.file])
  }
  const clashes = [...byFile.entries()].filter(([, papers]) => papers.length > 1)
  if (!clashes.length) return
  throw new Error(
    `${clashes.length} batch filename(s) claimed by more than one paper — one would overwrite the other:\n`
    + clashes.map(([file, papers]) => `  ${file}: ${papers.join(' and ')}`).join('\n'))
}

/**
 * The question-book leaves belonging to one module.
 *
 * `seeds/mcq/` is not itself scoped by module — it was written when there was
 * only 101 — so a leaf is claimed by the module its own `modulePath` names.
 * That is the same string the batch writes to `module_subject`, so a leaf
 * cannot be filed under one module here and another at import. Moving the
 * directory to `seeds/mcq/<module>/` is the tidier fix and is a file move,
 * which this port deliberately did not make.
 */
async function mcqLeaves(module: string): Promise<{ leaf: McqLeafSeed, name: string }[]> {
  const dir = 'scripts/kasr/seeds/mcq'
  if (!existsSync(dir)) return []
  const found: { leaf: McqLeafSeed, name: string }[] = []
  for (const name of readdirSync(dir).filter((one) => one.endsWith('.ts')).sort()) {
    const leaf = (await import(`./seeds/mcq/${name}`)).LEAF as McqLeafSeed
    if (leaf.modulePath.startsWith(`${module} > `) || leaf.modulePath === module) {
      found.push({ leaf, name })
    }
  }
  return found
}

/**
 * The multiple-choice bank, one batch per subject-tree leaf.
 *
 * Machine extraction supplies stems, options and most answers; the leaf seeds
 * under `seeds/mcq/` supply what an author has to decide — which concept a
 * question tests and why each option is right or wrong. A question with no
 * per-option explanation teaches a student nothing beyond "not that one", so
 * the emitter refuses to write one.
 */
async function mcq(module: ModuleRef) {
  // Checked before the bank is opened. The bank is one file per module and
  // reading another module's would be exactly the cross-module read the `load`
  // thunk in the registry exists to prevent.
  const leaves = (await mcqLeaves(module.id)).map((one) => one.leaf)
  if (!leaves.length) return null

  const bankPath = 'scripts/kasr/extract/mcq-bank.json'
  if (!existsSync(bankPath)) return null
  const bank = new Map<string, BankRow>(
    JSON.parse(readFileSync(bankPath, 'utf8')).questions.map((row: BankRow) => [row.key, row]))

  // Concepts first: their exam signal is every occurrence of every question
  // that tests them, which is the whole reason a question book is worth
  // reading at all — one book asking a thing five times is blueprint evidence
  // no single paper can give.
  const conceptBlocks: string[] = []
  const questionBlocks: string[] = []
  let excluded = 0
  let unanswered = 0

  /**
   * Concepts across every leaf, deduplicated by canonical key.
   *
   * Two leaves can legitimately test the same concept — a question about cilia
   * belongs equally to the cell and to membranous specialisations — and the
   * mint is a pure function of the key, so both produce the same ID. Emitting
   * one block per leaf therefore wrote the same concept twice into one file,
   * which the importer rejects as `duplicate id within the file`.
   *
   * Merged rather than de-duplicated by dropping one: the second leaf's
   * questions are more occurrences of the same objective, and those are the
   * blueprint evidence. Throwing them away to fix a duplicate row would lose
   * exactly what makes reading several question books worth doing.
   */
  const byKey = new Map<string, {
    concept: McqLeafSeed['concepts'][number]
    signals: Set<string>
    /**
     * Every article that teaches this concept, not the first leaf's.
     *
     * A concept two leaves share is taught from both sides, and the coverage
     * check asks whether a question's concept names an article the question
     * also cites. Keeping only one leaf's article left the other leaf's
     * questions reported as taught by nothing.
     */
    articleIds: Set<string>
    /** The books' own stems for this objective, best first. */
    stems: { stem: string; timesAsked: number }[]
  }>()

  for (const leaf of leaves) {
    const live = leaf.questions.filter((one) => !one.exclude)
    excluded += leaf.questions.length - live.length

    for (const concept of leaf.concepts) {
      const signals = live
        .filter((one) => one.conceptKey === concept.key)
        .flatMap((one) => bank.get(one.key)?.occurrences ?? [])
        .map((where) => `${where.sourceId} | question_book | | p${where.page} | ${module.id}`)
      // Merged across leaves, not emitted per leaf. Two leaves may correctly
      // reuse one concept — `cilium-origin-and-ultrastructure` is tested from
      // both the cytoplasm and the membranous-specialisations side — and
      // emitting it twice put two rows with one id in the batch, which the
      // importer would apply as a record overwriting itself. The paper path
      // has always deduplicated by key; this one did not.
      // Every question, not only the live ones. An excluded question's stem is
      // still the examiner's words — exclusion is about whether the item can be
      // answered, not about who wrote it — and four concepts had no
      // `original_wording` at all because every question testing them was set
      // aside.
      const stems = leaf.questions
        .filter((one) => one.conceptKey === concept.key)
        .map((one) => bank.get(one.key))
        .filter((row): row is NonNullable<typeof row> => Boolean(row?.stem))
        .map((row) => ({ stem: row.stem, timesAsked: row.timesAsked ?? 1 }))

      const found = byKey.get(concept.key)
      if (found) {
        for (const signal of signals) found.signals.add(signal)
        found.articleIds.add(leaf.articleId)
        found.stems.push(...stems)
      } else {
        byKey.set(concept.key, {
          concept, signals: new Set(signals), articleIds: new Set([leaf.articleId]), stems,
        })
      }
    }

    for (const authored of live) {
      const row = bank.get(authored.key)
      if (!row) throw new Error(`${leaf.leaf}: ${authored.key} is not in the bank`)
      if (!authored.answerOverride && !row.answer) { unanswered += 1; continue }
      questionBlocks.push(mcqBlock(row, authored, leaf, module))
    }
  }

  /**
   * A leaf may declare a concept no question in it tests.
   *
   * Three did, and all three are already minted from a sat paper, where they
   * carry the examiner's printed wording. The question-book copy has none —
   * there is no question to take it from — so it fails the audit on
   * `original_wording` while adding nothing the paper batch does not already
   * say. Skipped rather than emitted empty, and named, because a concept
   * declared and never tested is worth someone noticing.
   */
  const untested = [...byKey.entries()].filter(([, entry]) => !entry.stems.length)
  for (const [key] of untested) byKey.delete(key)

  for (const { concept, signals, articleIds, stems } of byKey.values()) {
    // The books' own wording for this objective: the stem of the question asked
    // most often. `original_wording` is the examiner's words, and for a concept
    // minted from question books this is where those words live — the paper
    // path takes the same field from the paper's printed question.
    const best = [...stems].sort((a, b) => b.timesAsked - a.timesAsked)[0]
    const asked = best ? `[asked ${best.timesAsked}x across the question books] ${best.stem}` : ''
    const reading = furtherReading()
    conceptBlocks.push(mcqConceptBlock(module, concept, [...signals], [...articleIds].join(' | '), asked,
      [...new Set([...articleIds].flatMap((id) => reading.get(id) ?? []))]))
  }

  const header = `Multiple-choice questions for ${module.id}, from the departmental question books.

${leaves.map((leaf) => `  ${leaf.leaf} — ${leaf.questions.length} questions, ${leaf.concepts.length} concepts`).join('\n')}

Extracted from ${bank.size} distinct questions across thirty question books and
deduplicated: the same question appears in as many as five of them, and the books
copy each other freely. Every item carries how many times it was asked, which is
blueprint evidence no single sat paper can give.

Stems, options and answers are the books'. Every per-option explanation is
authored: a student who picks a wrong option and is told only that it was wrong
has learnt nothing, so a distractor's explanation says what would make someone
pick it.

${excluded} question${excluded === 1 ? ' was' : 's were'} excluded and ${unanswered} held back for having no
establishable answer. Both stay in the seeds with their reasons rather than being
deleted — a question dropped silently is one nobody can reconsider.

Status is Draft throughout: these need a faculty reviewer before students sit them.

${GENERATED_BY}.`

  mkdirSync(`${OUT}/concept`, { recursive: true })
  mkdirSync(`${OUT}/question`, { recursive: true })
  const conceptFile = `${OUT}/concept/${fileSlug(module.id)}-mcq-concepts.md`
  const questionFile = `${OUT}/question/${fileSlug(module.id)}-mcq.md`
  writeFileSync(conceptFile, batchFile(header, conceptBlocks))
  writeFileSync(questionFile, batchFile(header, questionBlocks))
  for (const [key] of untested) {
    console.log(`  skipped concept "${key}" — declared by a leaf but no question tests it`)
  }
  return { conceptFile, questionFile, concepts: conceptBlocks.length, questions: questionBlocks.length, excluded, unanswered }
}

/**
 * Delete this module's written batches that this run did not write.
 *
 * The slug is derived from the paper's tier, and when the tier of a paper
 * changed — a resit that had been filed as an end-of-module — the old file
 * stayed behind. Two files then held the same paper under different names,
 * with the same manifest ID and the same question IDs, and the validator was
 * perfectly happy with both. A duplicated sitting doubles its blueprint weight,
 * which is the one number this whole programme exists to get right.
 *
 * Generated output that outlives its generator is not a stale file, it is a
 * second copy of the truth.
 *
 * **Scoped to the module being built.** Unscoped, a `101 ISK` run deletes every
 * other module's written batches, because this run did not write them — which
 * is the neighbour-clobbering failure the required module argument exists to
 * stop, arriving by the back door.
 */
function removeOrphans(module: string, written: Set<string>, sweep: boolean) {
  const dir = `${OUT}/written`
  if (!existsSync(dir)) return []
  const prefix = `${fileSlug(module)}-`
  const orphans = readdirSync(dir)
    // This module's own output, and nothing else.
    //
    // `written/` holds other modules' batches now, and this generator used to
    // know only about 101 ISK papers — so every 104 CPS and 108 INT file in the
    // directory looked like output whose paper had been unregistered, and got
    // swept. `108-INT-EOY-written.md` was deleted twice this way; the second
    // time the deletion was pushed. A sweep that cannot tell "no longer
    // generated" from "generated by someone else" must not be allowed to
    // delete anything.
    //
    // Scoped by the same value the filenames are built from, so the sweep and
    // the slug cannot drift apart — the registry has been incomplete three
    // times now, and completeness is not a property anyone can hold across six
    // lanes. A sweep that cannot *reach* another module's prefix does not need
    // the registry to be right.
    //
    // Derived from the module being built rather than a `'101-ISK'` constant,
    // now that the module is a parameter: the constant solved this for one
    // module and would have had to be edited, or forgotten, for every other.
    .filter((name) => name.startsWith(prefix) && name.endsWith('-written.md'))
    .filter((name) => !written.has(`${dir}/${name}`))
    // And only files this generator wrote.
    //
    // The prefix filter answered "can a 101 build delete a 104 file". It does
    // not answer "can a 101 build delete a hand-authored 101 file", and the
    // same question arrives for every module the moment one of its papers is
    // registered: `108-INT-EOY-written.md` is hand-authored and shares the
    // prefix its own build would sweep under. Six such files are sitting in
    // this directory today, each safe only because nobody has registered a
    // paper for its module yet.
    //
    // Generated batches say so in their header — `batchFile` writes the line
    // below into every one — and a hand-authored batch does not. So the sweep
    // can finally tell "no longer generated" from "never generated", which is
    // the distinction its own rule demanded and it did not have. Anything
    // without the marker is reported and left alone.
    .filter((name) => {
      const generated = readFileSync(`${dir}/${name}`, 'utf8').includes(GENERATED_BY)
      if (!generated) {
        console.log(`left alone (not generated by this script): written/${name}`)
      }
      return generated
    })
  // Reporting is the default; deleting takes `--sweep`.
  //
  // The marker separates "never generated" from "no longer generated". It
  // cannot see a third state, found by the lane that found the second: a file
  // whose header truthfully claims this generator wrote it, for a registration
  // that is no longer in `registry.ts`. `104-CPS-EOY-2025-written.md` is
  // exactly that — a real generator header, and `build-batches.ts "104 CPS"`
  // throws `no registered paper belongs to "104 CPS"`. The marker waves it
  // through, and nothing can rebuild it afterwards.
  //
  // No predicate closes that, because the file's claim about its own origin is
  // true and what changed is the generator's ability to honour it. What can be
  // closed is the consequence. A stale batch is untidy and says so in its own
  // header; a deleted one is gone, and this sweep has deleted three of other
  // lanes' files in a day, each time inside a regeneration diff too large for
  // the `D` line to be seen. Untidy is the cheaper failure and it is the one
  // that leaves evidence.
  if (!sweep) {
    for (const name of orphans) {
      console.log(`orphaned batch, left in place: written/${name}`)
    }
    if (orphans.length) {
      console.log(`  ${orphans.length} orphan(s) — rerun with --sweep to delete them`)
    }
    return []
  }
  for (const name of orphans) rmSync(`${dir}/${name}`)
  return orphans
}

// Grouped by module, filtered *before* loading — see `Registration` in
// `seeds/registry.ts`.
const only = process.argv[2]
if (!only) {
  throw new Error('name the module to build — one of '
    + `${[...new Set(REGISTRATIONS.map((entry) => entry.module))].map((id) => `"${id}"`).join(', ')}. `
    + 'There is no build-everything mode: five lanes share this script, and a bare run '
    + "rewrote every module's batches including ones another lane had already finished.")
}
if (!MODULES[only]) {
  throw new Error(`"${only}" is not a module in the catalogue — one of ${Object.keys(MODULES).join(', ')}`)
}
const wanted = REGISTRATIONS.filter((entry) => entry.module === only)
if (!wanted.length) throw new Error(`no registered paper belongs to "${only}"`)

const papers: Paper[] = []
for (const entry of wanted) {
  const paper = entry.load()
  const id = moduleOf(paper.source).id
  // The registration and the paper must agree, or the filter above silently
  // did the wrong thing: a paper registered under one module and carrying
  // another would be skipped by the module it belongs to and built by the one
  // it does not.
  if (id !== entry.module) {
    throw new Error(`${paper.source.file}: registered under "${entry.module}" but carries "${id}"`)
  }
  papers.push(paper)
}

// Every question must have a mark scheme before anything is written, so a
// paper missing one fails before it has half-written a batch file.
for (const paper of papers) {
  for (const seed of paper.seeds) {
    if (!paper.schemes[partsKey(seed)]) {
      throw new Error(`${paper.source.file}: ${partsKey(seed)} has no mark scheme`)
    }
  }
}

assertNoSlugCollision(papers)
await assertOneSubjectPerKey(only, papers)

const c = concepts(only, papers)
console.log(`${c.count} concepts (${c.repeated} repeated across papers) -> ${c.file}`)
const writtenFiles = new Set<string>()
for (const paper of papers) {
  const w = written(paper)
  writtenFiles.add(w.file)
  console.log(`${w.count} written questions, ${w.marks} marks -> ${w.file}`)
}
for (const orphan of removeOrphans(only, writtenFiles, process.argv.includes('--sweep'))) {
  console.log(`removed orphaned batch (no paper produces it any more): written/${orphan}`)
}

const m = await mcq(MODULES[only])
if (m) {
  console.log(`${m.concepts} MCQ concepts -> ${m.conceptFile}`)
  console.log(`${m.questions} MCQ questions (${m.excluded} excluded, ${m.unanswered} unanswered) -> ${m.questionFile}`)
}
